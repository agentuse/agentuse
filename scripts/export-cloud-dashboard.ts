/**
 * Exports the built dashboard (dist/web) for AgentUse Cloud, which serves the
 * same web app at cloud.agentuse.io in cloud mode (src/cli/serve/web/lib/cloud.ts).
 *
 * Usage: bun scripts/export-cloud-dashboard.ts <out-dir>
 *
 * Run `bun run build:web` first. Writes:
 *   <out-dir>/public/assets/*      the hashed bundle (no .br/.gz: Cloudflare compresses)
 *   <out-dir>/public/sw.js, favicon.svg, manifest.webmanifest, icon PNGs
 *   <out-dir>/dashboard-shell.ts   the HTML shell as a module, with two
 *                                  placeholders the Worker fills per request:
 *                                  the CSP nonce and the shell data
 *
 * agentuse-cloud's `scripts/sync-dashboard.mjs` runs this from a pinned
 * agentuse-lab commit and commits the result.
 */
import { copyFile, mkdir, readFile, rm, writeFile } from "fs/promises";
import { join, resolve } from "path";
import { renderShellHtml, type WebManifest } from "../src/cli/serve/static";
import { SERVICE_WORKER_JS } from "../src/cli/serve/push";
import { FAVICON_SVG, ICON_192_PNG_BASE64, ICON_512_PNG_BASE64, TOUCH_ICON_180_PNG_BASE64, webManifestJson } from "../src/cli/serve/brand";
import { version } from "../package.json";

/** Filled by the Cloud Worker per request. */
export const NONCE_PLACEHOLDER = "__AGENTUSE_CSP_NONCE__";
export const CLOUD_JSON_PLACEHOLDER = "__AGENTUSE_CLOUD_JSON__";

const ROOT = resolve(import.meta.dir, "..");
const WEB = join(ROOT, "dist/web");

async function main(): Promise<void> {
  const outArg = process.argv[2];
  if (!outArg) throw new Error("Usage: bun scripts/export-cloud-dashboard.ts <out-dir>");
  const out = resolve(outArg);
  const manifest = JSON.parse(await readFile(join(WEB, "manifest.json"), "utf-8")) as WebManifest;

  const publicDir = join(out, "public");
  await rm(join(publicDir, "assets"), { recursive: true, force: true });
  await mkdir(join(publicDir, "assets"), { recursive: true });
  for (const file of manifest.files) {
    if (file.endsWith(".br") || file.endsWith(".gz")) continue;
    await mkdir(join(publicDir, "assets", file, ".."), { recursive: true });
    await copyFile(join(WEB, file), join(publicDir, "assets", file));
  }

  await writeFile(join(publicDir, "sw.js"), SERVICE_WORKER_JS);
  await writeFile(join(publicDir, "favicon.svg"), FAVICON_SVG);
  await writeFile(join(publicDir, "manifest.webmanifest"), webManifestJson());
  await writeFile(join(publicDir, "apple-touch-icon.png"), Buffer.from(TOUCH_ICON_180_PNG_BASE64, "base64"));
  await writeFile(join(publicDir, "icon-192.png"), Buffer.from(ICON_192_PNG_BASE64, "base64"));
  await writeFile(join(publicDir, "icon-512.png"), Buffer.from(ICON_512_PNG_BASE64, "base64"));

  const shell = renderShellHtml(manifest, { nonce: NONCE_PLACEHOLDER, cloudJson: CLOUD_JSON_PLACEHOLDER });
  await writeFile(join(out, "dashboard-shell.ts"), [
    "// Generated by agentuse-lab scripts/export-cloud-dashboard.ts. Do not edit; run `pnpm sync:dashboard`.",
    `export const DASHBOARD_VERSION = ${JSON.stringify(version)};`,
    `export const NONCE_PLACEHOLDER = ${JSON.stringify(NONCE_PLACEHOLDER)};`,
    `export const CLOUD_JSON_PLACEHOLDER = ${JSON.stringify(CLOUD_JSON_PLACEHOLDER)};`,
    `export const DASHBOARD_SHELL = ${JSON.stringify(shell)};`,
    "",
  ].join("\n"));
  console.log(`Exported the dashboard (${manifest.files.length} files, AgentUse ${version}) to ${out}`);
}

await main();
