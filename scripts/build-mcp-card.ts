/**
 * Bundles the MCP cards into self-contained HTML pages in src/generated.
 * Cards run in an app's sandboxed frame, with inline scripts and no imports.
 * Run after changing the card: `bun scripts/build-mcp-card.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const cardDir = resolve(root, 'src/mcp-server/card');

for (const [name, exportName] of [['draft-card', 'DRAFT_CARD_HTML'], ['context-picker', 'CONTEXT_PICKER_HTML']] as const) {
  const built = await Bun.build({
    entrypoints: [resolve(cardDir, `${name}.ts`)],
    target: 'browser',
    format: 'iife',
    minify: true,
  });
  if (!built.success) {
    for (const log of built.logs) console.error(log);
    throw new Error('Card bundle failed');
  }
  const script = await built.outputs[0]!.text();
  if (script.includes('</script')) throw new Error('Card bundle contains a closing script tag');

  const template = readFileSync(resolve(cardDir, `${name}.html`), 'utf8');
  const html = template.replace('/*__CARD_SCRIPT__*/', () => script);

  writeFileSync(
    resolve(root, `src/generated/mcp-${name}.ts`),
    `// Generated by scripts/build-mcp-card.ts from src/mcp-server/card. Do not edit.\nexport const ${exportName} = ${JSON.stringify(html)};\n`,
  );
  console.log(`Wrote src/generated/mcp-${name}.ts (${Math.round(html.length / 1024)} KB)`);
}
