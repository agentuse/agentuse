/**
 * Bundles the MCP "Turn on" card (src/mcp-server/card) into one self-contained
 * HTML page and writes it to src/generated/mcp-draft-card.ts. The card runs in
 * an app's sandboxed frame, so its script must be inline with no imports.
 * Run after changing the card: `bun scripts/build-mcp-card.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const cardDir = resolve(root, 'src/mcp-server/card');

const built = await Bun.build({
  entrypoints: [resolve(cardDir, 'draft-card.ts')],
  target: 'browser',
  format: 'iife',
  minify: true,
});
if (!built.success) {
  for (const log of built.logs) console.error(log);
  throw new Error('Card bundle failed');
}
const script = await built.outputs[0]!.text();
if (script.includes('</script')) throw new Error('Card bundle contains a closing script tag');

const template = readFileSync(resolve(cardDir, 'draft-card.html'), 'utf8');
const html = template.replace('/*__CARD_SCRIPT__*/', () => script);

writeFileSync(
  resolve(root, 'src/generated/mcp-draft-card.ts'),
  `// Generated by scripts/build-mcp-card.ts from src/mcp-server/card. Do not edit.\nexport const DRAFT_CARD_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote src/generated/mcp-draft-card.ts (${Math.round(html.length / 1024)} KB)`);
