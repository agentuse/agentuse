/** Export the real MCP tool descriptors for Cloud, including while computers are offline. */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createAgentUseMcpServer } from '../src/mcp-server/server';

const server = createAgentUseMcpServer({
  get: async () => { throw new Error('Catalog generation must not contact a daemon'); },
  post: async () => { throw new Error('Catalog generation must not contact a daemon'); },
});
const client = new Client({ name: 'agentuse-catalog-build', version: '1.0.0' });
const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
try {
  await server.connect(serverTransport);
  await client.connect(clientTransport);
  const { tools } = await client.listTools();
  writeFileSync(
    resolve(import.meta.dir, '../src/generated/mcp-tool-catalog.ts'),
    `// Generated by scripts/build-mcp-catalog.ts from the MCP server. Do not edit.\nexport const MCP_TOOL_CATALOG = ${JSON.stringify(tools, null, 2)};\n`,
  );
  console.log(`Wrote src/generated/mcp-tool-catalog.ts (${tools.length} tools)`);
} finally {
  await client.close();
  await server.close();
}
